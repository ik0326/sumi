#!/usr/bin/env python3
"""Writes web/src/themes.css from web/src/themes.json.  Run from web/:  npm run themes

Each theme has a light and a dark palette. The dark one is used when the app is dark,
or when the editor is forced with data-scheme="dark" (and the reverse for "light").
"""
import json, os

web = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
themes = json.load(open(os.path.join(web, "src", "themes.json")))

def rules(selector, palette, indent=""):
    body = "".join(f"{indent}  {k}: {v};\n" for k, v in palette.items())
    return f"{indent}{selector} {{\n{body}{indent}}}\n"

out = "/* Generated by scripts/themes.py from themes.json — do not edit. */\n"
for name, t in themes.items():
    sel = ":root" if name == "default" else f':root[data-theme="{name}"]'
    out += rules(sel, t["light"])
    out += "@media (prefers-color-scheme: dark) {\n" + rules(sel + ':not([data-scheme="light"])', t["dark"], "  ") + "}\n"
    out += rules(sel + '[data-scheme="dark"]', t["dark"]) + "\n"
open(os.path.join(web, "src", "themes.css"), "w").write(out)
# The app reads the same palettes for the sidebar, the note list and the headers.
json.dump(themes, open(os.path.join(os.path.dirname(web), "Sumi", "Resources", "editor", "themes.json"), "w"), indent=1)
print(len(themes), "themes")
